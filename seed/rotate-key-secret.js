/* Rotate KEY_ENCRYPTION_SECRET without orphaning the key inventory.
   Every GameKey row stores `iv.tag.cipher` encrypted under the old secret.
   Swapping the secret alone would make all of them undecryptable the moment
   one is sold, so this re-encrypts them in place and verifies each one.

   Dry run by default. Apply with --apply.

   Usage:
     set OLD_KEY_ENCRYPTION_SECRET=<current value>
     set NEW_KEY_ENCRYPTION_SECRET=<new value>
     node seed/rotate-key-secret.js            (reports what would change)
     node seed/rotate-key-secret.js --apply    (rewrites + updates .env)   */
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const mongoose = require('mongoose');

const APPLY = process.argv.includes('--apply');
const OLD_RAW = process.env.OLD_KEY_ENCRYPTION_SECRET || process.env.KEY_ENCRYPTION_SECRET;
const NEW_RAW = process.env.NEW_KEY_ENCRYPTION_SECRET;
const ENV_PATH = path.join(__dirname, '..', '.env');

const derive = (raw) => crypto.createHash('sha256').update(String(raw)).digest();

function encrypt(plain, key) {
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const enc = Buffer.concat([cipher.update(String(plain), 'utf8'), cipher.final()]);
  return `${iv.toString('base64')}.${cipher.getAuthTag().toString('base64')}.${enc.toString('base64')}`;
}

function decrypt(payload, key) {
  const [iv, tag, data] = String(payload).split('.');
  const d = crypto.createDecipheriv('aes-256-gcm', key, Buffer.from(iv, 'base64'));
  d.setAuthTag(Buffer.from(tag, 'base64'));
  return Buffer.concat([d.update(Buffer.from(data, 'base64')), d.final()]).toString('utf8');
}

(async () => {
  if (!OLD_RAW) { console.error('No OLD_KEY_ENCRYPTION_SECRET (and no KEY_ENCRYPTION_SECRET in .env).'); process.exit(1); }
  if (!NEW_RAW) { console.error('No NEW_KEY_ENCRYPTION_SECRET set.'); process.exit(1); }
  if (String(NEW_RAW).length < 32) { console.error('NEW_KEY_ENCRYPTION_SECRET must be at least 32 characters.'); process.exit(1); }
  if (OLD_RAW === NEW_RAW) { console.error('Old and new secret are identical — nothing to do.'); process.exit(1); }

  const oldKey = derive(OLD_RAW);
  const newKey = derive(NEW_RAW);

  await mongoose.connect(process.env.MONGO_URI);
  const rows = await mongoose.connection.db.collection('gamekeys').find({}).toArray();
  console.log(`${APPLY ? 'Applying' : 'Dry run'}: ${rows.length} key rows found.`);

  const plan = [];
  let undecryptable = 0;
  for (const r of rows) {
    let plain;
    try { plain = decrypt(r.codeEnc, oldKey); }
    catch {
      undecryptable++;
      // Already written with a different secret (or corrupt). Re-encrypt blind is
      // impossible, so it must be regenerated by the caller instead.
      continue;
    }
    const check = decrypt(encrypt(plain, newKey), newKey);
    if (check !== plain) { console.error('Round-trip failed, aborting before any write.'); process.exit(1); }
    plan.push({ _id: r._id, codeEnc: encrypt(plain, newKey) });
  }

  if (undecryptable) {
    console.error(`${undecryptable} row(s) could not be decrypted with the old secret.`);
    console.error('Abort. Re-seed those keys (node seed/import-steam.js) rather than rotating.');
    process.exit(1);
  }
  if (!plan.length) { console.log('Nothing to rotate.'); await mongoose.disconnect(); process.exit(0); }

  if (!APPLY) {
    console.log('Dry run only. Re-run with --apply to write.');
    console.log('Sample plaintext of the first key: ' + decrypt(rows[0].codeEnc, oldKey));
    await mongoose.disconnect();
    process.exit(0);
  }

  const col = mongoose.connection.db.collection('gamekeys');
  for (const p of plan) await col.updateOne({ _id: p._id }, { $set: { codeEnc: p.codeEnc } });
  console.log(`Re-encrypted ${plan.length} rows.`);

  const after = await col.find({}).limit(3).toArray();
  for (const r of after) console.log('  verifies under new secret: ' + decrypt(r.codeEnc, newKey));

  if (fs.existsSync(ENV_PATH)) {
    const text = fs.readFileSync(ENV_PATH, 'utf8');
    const next = text.replace(/^KEY_ENCRYPTION_SECRET=.*$/m, `KEY_ENCRYPTION_SECRET=${NEW_RAW}`);
    if (next !== text) { fs.writeFileSync(ENV_PATH, next); console.log('.env updated.'); }
    else console.log('KEY_ENCRYPTION_SECRET line not found in .env — update it by hand.');
  }
  await mongoose.disconnect();
})().catch((e) => { console.error('Failed:', e.message); process.exit(1); });